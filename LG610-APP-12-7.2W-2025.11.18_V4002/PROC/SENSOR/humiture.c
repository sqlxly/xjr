const float canKaoTemp[18]={35,34.3,33.6,32.9,32.2,31.5,30.8,30.1,29.4,28,27.3,26.6,25.9,25.3,24.6,23.9,22.5,21.1};//参考温度

int16_t tiWenCalc(float temp,float shidu,float fanSpeed)//风速单位  m/s 
{ 
   if((temp>35.0f)||(temp<21.1f)||(shidu>=80.0f)||(shidu<30.0f)||(fanSpeed<0.0f)||(fanSpeed>=2.5f)) 
   { 
      return 9999; 
   } 
   else 
   { 
      float tempOffset=0; 
      unsigned char i=0; 
      unsigned char fanAre=0; 
      unsigned char shiDuAre=0; 
      unsigned char tempAre=0; 
      unsigned char lineNum=0; 
      float fanS1=0,fanS2=0,shiDu1=0,shiDu2=0; 
      float a1=0,a2=0,b1=0,b2=0; 
      float A1=0,A2=0; 
      float A0=0; 
      for(i=0;i<18;i++)//计算温度漂移量,和寻找温度所在区间 
      { 
         if(temp>=canKaoTemp[i]) 
         { 
            tempOffset=temp-canKaoTemp[i]; 
            tempAre=i; 
            break; 
         } 
					else 
         { 
            tempAre=17; 
         } 
      } 
      for(i=0;i<11;i++)//寻找风速所在区间--列号 
      { 
         if(fanSpeed>=fanSpeed1[10-i]) 
         { 
            fanAre=10-i; 
            fanS1=fanSpeed1[10-i]; 
            fanS2=fanSpeed1[10-i+1]; 
            break; 
         } 
      } 
      { 
         if(i==0) 
         { 
            fanAre-=1; 
            fanS2=fanS1; 
         } 
      } 
      for(i=0;i<6;i++)//寻找湿度所在区间 
      { 
         if(shidu>=canKaoShiDu[5-i]) 
				 { 
            shiDuAre=5-i; 
            shiDu1=canKaoShiDu[5-i]; 
            shiDu2=canKaoShiDu[5-i+1]; 
            break; 
         } 
      } 
      
		  if(i==0)//表示湿度大于80，不在表以内 
		  { 
				shiDuAre-=1; 
				shiDu2=shiDu1; 
		  } 
      
      lineNum=tempAre*6+shiDuAre+1;//计算所在行号  lineNum<x<lineNum+1 
      a1=tiWenTable[lineNum][fanAre]; 
      a2=tiWenTable[lineNum][fanAre+1]; 
      b1=tiWenTable[lineNum+1][fanAre]; 
      b2=tiWenTable[lineNum+1][fanAre+1]; 
      A1=a1+((shidu-shiDu1)/(shiDu2-shiDu1))*(b1-a1); 
      A2=a2+((shidu-shiDu1)/(shiDu2-shiDu1))*(b2-a2); 

			A0=A1+((fanSpeed-fanS1)/(fanS2-fanS1))*(A2-A1); 
      A0+=tempOffset; 
      return (A0*10); 
   } 
}

