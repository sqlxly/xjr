void FloatToFourByte(float floatNum, unsigned char* byteArry)
{
	char *pchar = (char*)&floatNum;
	for (int i = 0;i<sizeof(float);i++)
	{
		*byteArry = *pchar;
		pchar++;
		byteArry++;
	}
}
float hexToFloatInverse(unsigned char *content)
{
	union lhex
	{
		unsigned char d[4];
		float f;
	}fdata;
	
	unsigned char buf_tmp[5];	
	buf_tmp[0]=content[1];
	buf_tmp[1]=content[0];
	buf_tmp[2]=content[3];
	buf_tmp[3]=content[2];
	buf_tmp[4]=0;
	
	for (int i = 0; i < 4; i++)
	{
		fdata.d[i] = buf_tmp[3-i];
	}
	//rt_kprintf("float_number:%f\r\n",fdata.f);
	return fdata.f;
}

