unsigned int server_crc_chk(unsigned char* data, unsigned short int length)
{
	uint16_t j;
	uint16_t reg_tmp=0xffff;
	union CONVERSE converse_tmp;
	uint16_t reg_crc=0xffff;
	while(length--)
	{
		reg_crc ^= *data++;
		for (j=0;j<8;j++)
		{
			if (reg_crc & 0x01) 
			{
				reg_crc=(reg_crc>>1) ^ 0xa001;//0xA = 1010;  0xA001   = 1010 0000 0000 0001
			}
			else 
			{
				reg_crc=reg_crc >>1;
			}
		}
	}
	reg_tmp=reg_crc;
	converse_tmp.data[1]=reg_tmp&0x00ff;
	converse_tmp.data[0]=(reg_tmp&0xff00)>>8;
	//DEBUG("modbus_crc=%04X\r\n",converse_tmp.value);
	return converse_tmp.value;  // the value that sent back to the CRC register finally
}
unsigned int crc_chk(unsigned char* data, unsigned short int length)
{
	int j;
	unsigned int reg_crc=0xffff;
	while(length--)
	{
		reg_crc ^= *data++;
		for (j=0;j<8;j++)
		{
			if (reg_crc & 0x01) 
			{
				reg_crc=(reg_crc>>1) ^ 0xa001;//0xA = 1010;  0xA001   = 1010 0000 0000 0001
			}
			else 
			{
				reg_crc=reg_crc >>1;
			}
		}
	}
	//DEBUG("crc=%04X\r\n",reg_crc);
	return reg_crc;  // the value that sent back to the CRC register finally
}
