// 连续写伺服电机寄存器
 //LEN 不是字节 而是写寄存器个数  u16 类型
rt_err_t rs4851_write_mutly_regs(uint8_t id,uint16_t addr, uint16_t *dat,uint16_t len)
{
	uint8_t nb;
	int tx_len=0,read_len;
	
	agile_modbus_set_slave(ctx1, id);
  tx_len =  agile_modbus_serialize_write_registers(ctx1,  addr,  len, dat);
  rs4851_clear_buf();
	rs4851_send_dat(ctx1->send_buf, tx_len);
	read_len = rs4851_read_dat(ctx1->read_buf, ctx1->read_bufsz,MODBUS_TIMEOUT);
	if (read_len <= 0) {
            DEBUG_WARN("RS4851 write  failed slav id=%d result= no recive\n",id);
            return RT_ERROR;
  }
	int rc = agile_modbus_deserialize_write_register(ctx1, read_len);
   if (rc < 0) {
								DEBUG_WARN("RS4851 write buf failed  id=%d result = data err read len=%d\n",id,read_len);
								rt_thread_mdelay(5);
								return RT_ERROR;
    }
	 else 
	 {
			rt_kprintf("mb write buf scuess.\n");
			return RT_EOK;
	 }
}


